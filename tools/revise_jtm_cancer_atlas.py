def find(document, prefix: str):
    matches = [p for p in document.paragraphs if p.text.startswith(prefix)]
    if len(matches) != 1:
        raise ValueError(f"Expected one paragraph starting {prefix!r}; found {len(matches)}")
    return matches[0]


def insert_after(paragraph, text: str):
    new = paragraph.insert_paragraph_before(text)
    paragraph._p.addnext(new._p)
    new.style = paragraph.style
    return new


def put_text(paragraph, text: str):
    paragraph.text = text


def read_catalogue():
    with CATALOGUE.open(newline="", encoding="utf-8") as handle:
        rows = list(csv.DictReader(handle))
    assert len(rows) == 1084
    assert sum(row["tumor_type"] == "BRCA" for row in rows) == 72
    assert sum(row["tumor_type"] == "CHOL" for row in rows) == 8
    assert sum(row["same_histology_modality"].upper() == "FALSE" for row in rows) == 1072
    return rows


